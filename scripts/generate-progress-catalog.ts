import { writeFileSync } from 'node:fs';
import { missions } from '../src/learning';
import { courses } from '../src/courses';
import { modulesFor } from '../src/curriculum';
import { drawingActivities } from '../src/drawingActivities';
// Generated from the shipped curriculum; no second hand-maintained list of IDs.
const catalog = Object.fromEntries(courses.map(course => [course.id, {
  challenges: modulesFor(course.id).flatMap(module => module.challengeIds),
  missions: missions.flatMap((mission, index) => mission.id.startsWith(`${course.id}-`) ? [{ id: mission.id, index, title: mission.title, size: mission.size }] : []),
  drawings: drawingActivities[course.id].map(activity => ({ id: activity.id, title: activity.title })),
}]));
writeFileSync(new URL('../shared/progress-catalog.ts', import.meta.url), `// Generated by scripts/generate-progress-catalog.ts.\nexport const progressCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`);
